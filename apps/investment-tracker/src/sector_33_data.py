# 逆引き用（業種名 -> 指数コード）
SECTOR_33_NAMES_TO_CODES = {v: k for k, v in SECTOR_33_CODES.items()}


def get_sector_name(index_code: str) -> str:
    """
    指数コードから業種名を取得

    Args:
        index_code: 指数コード（例: "0040"）

    Returns:
        業種名（例: "水産・農林業"）
    """
    return SECTOR_33_CODES.get(index_code, "不明")


def get_index_code(sector_name: str) -> str:
    """
    業種名から指数コードを取得

    Args:
        sector_name: 業種名（例: "水産・農林業"）

    Returns:
        指数コード（例: "0040"）
    """
    return SECTOR_33_NAMES_TO_CODES.get(sector_name, "")


def get_all_sector_codes() -> list:
    """
    全33業種の指数コードリストを取得

    Returns:
        指数コードのリスト（例: ["0040", "0041", ...]）
    """
    return list(SECTOR_33_CODES.keys())
