"""東証33業種指数マスターデータ

J-Quants API の指数コード（16進数: 0040〜0060）と業種名のマッピング

重要: コードは16進数表記
- 0040-0049（数字）
- 004A-004F（A=10, B=11, C=12, D=13, E=14, F=15）
- 0050-0059（数字）
- 005A-005F（A=10, B=11, C=12, D=13, E=14, F=15）
- 0060（サービス業）
合計33業種
"""

# 東証33業種指数の指数コード（16進数）と業種名
SECTOR_33_CODES = {
    # 0040-0049（数字コード）
    "0040": "水産・農林業",
    "0041": "鉱業",
    "0042": "建設業",
    "0043": "食料品",
    "0044": "繊維製品",
    "0045": "パルプ・紙",
    "0046": "化学",
    "0047": "医薬品",
    "0048": "石油・石炭製品",
    "0049": "ゴム製品",
    # 004A-004F（16進数コード）
    "004A": "ガラス・土石製品",
    "004B": "鉄鋼",
    "004C": "非鉄金属",
    "004D": "金属製品",
    "004E": "機械",
    "004F": "電気機器",
    # 0050-0059（数字コード）
    "0050": "輸送用機器",
    "0051": "精密機器",
    "0052": "その他製品",
    "0053": "電気・ガス業",
    "0054": "陸運業",
    "0055": "海運業",
    "0056": "空運業",
    "0057": "倉庫・運輸関連業",
    "0058": "情報・通信業",
    "0059": "卸売業",
    # 005A-005F（16進数コード）
    "005A": "小売業",
    "005B": "銀行業",
    "005C": "証券・商品先物取引業",
    "005D": "保険業",
    "005E": "その他金融業",
    "005F": "不動産業",
    # 0060（最後の1業種）
    "0060": "サービス業"
}

# 逆引き用（業種名 -> 指数コード）
SECTOR_33_NAMES_TO_CODES = {v: k for k, v in SECTOR_33_CODES.items()}


def get_sector_name(index_code: str) -> str:
    """
    指数コードから業種名を取得

    Args:
        index_code: 指数コード（例: "0040", "004A"）

    Returns:
        業種名（例: "水産・農林業", "ガラス・土石製品"）
    """
    return SECTOR_33_CODES.get(index_code, "不明")


def get_index_code(sector_name: str) -> str:
    """
    業種名から指数コードを取得

    Args:
        sector_name: 業種名（例: "水産・農林業"）

    Returns:
        指数コード（例: "0040"）
    """
    return SECTOR_33_NAMES_TO_CODES.get(sector_name, "")


def get_all_sector_codes() -> list:
    """
    全33業種の指数コードリストを取得（16進数順）

    Returns:
        指数コードのリスト（例: ["0040", "0041", ..., "004A", ..., "0060"]）
    """
    # 16進数順にソート（0040, 0041, ..., 004A, 004B, ..., 005F, 0060）
    return sorted(SECTOR_33_CODES.keys())
