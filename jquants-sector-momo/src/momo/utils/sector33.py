def get_sector_name(sector_code: str) -> str:
    """
    業種コードから業種名を取得

    Args:
        sector_code: 4桁の業種コード（例：'3650'）

    Returns:
        str: 業種名（例：'電気機器'）存在しない場合は'不明'
    """
    return SECTOR33_MAPPING.get(str(sector_code).zfill(4), "不明")
